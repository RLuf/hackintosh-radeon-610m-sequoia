#!/usr/bin/env python3
"""Reconstruction of the missing scripts/dcn-remap.py of RembrandtGfx.

  dcn_remap_gen.py FROM_offset.h TO_offset.h [--check dcnremap.hpp] [--emit out.hpp] [--label X]

Pairs registers by NAME between two Linux DCN offset headers and lists the ones whose absolute
dword address (DCN segment base + offset) differs. DCN_BASE segments (same for 3.0.2/3.1.2/3.1.6
in Linux): 0x12, 0xC0, 0x34C0, 0x9000, 0x02403C00.
"""
import re, sys, argparse
BASE = [0x12, 0xC0, 0x34C0, 0x9000, 0x02403C00, 0]

def load(path):
    off, idx = {}, {}
    for l in open(path, errors='replace'):
        m = re.match(r'#define\s+(mm|reg)(\w+)\s+(0x[0-9a-fA-F]+|\d+)\s*$', l)
        if not m:
            continue
        name, v = m.group(2), int(m.group(3), 0)
        if name.endswith('_BASE_IDX'):
            idx[name[:-9]] = v
        else:
            off[name] = v
    return {n: BASE[idx[n]] + o for n, o in off.items() if n in idx}, {n: (idx[n], o) for n, o in off.items() if n in idx}

ap = argparse.ArgumentParser()
ap.add_argument('src'); ap.add_argument('dst')
ap.add_argument('--check'); ap.add_argument('--emit'); ap.add_argument('--label', default='?')
a = ap.parse_args()
src, srcraw = load(a.src)
dst, dstraw = load(a.dst)
rows = sorted((src[n], dst[n], n) for n in src if n in dst and src[n] != dst[n])
missing = sorted(n for n in src if n not in dst)
same = sum(1 for n in src if n in dst and src[n] == dst[n])
print('src regs %d, dst regs %d, same name+addr %d, moved %d, src-only names %d, dst-only names %d' % (
    len(src), len(dst), same, len(rows), len(missing), len([n for n in dst if n not in src])))
# collisions: a moved register's old address is occupied by another register in dst (needs the remap), or
# two src names share an address
byfrom = {}
for f, t, n in rows:
    byfrom.setdefault(f, []).append((t, n))
dup = {f: v for f, v in byfrom.items() if len(set(t for t, _ in v)) > 1}
print('distinct from-addresses %d, ambiguous (one from -> several to) %d' % (len(byfrom), len(dup)))
if a.check:
    ref = [(int(m.group(1), 16), int(m.group(2), 16), m.group(3)) for m in
           re.finditer(r'\{(0x[0-9a-f]+), (0x[0-9a-f]+), "(\w+)"\}', open(a.check).read())]
    rs, gs = set((f, t) for f, t, _ in ref), set((f, t) for f, t, _ in rows)
    print('check vs %s: ref %d entries, generated %d; pairs only in ref %d, only in generated %d' % (
        a.check.split('/')[-1], len(ref), len(rows), len(rs - gs), len(gs - rs)))
    for f, t in sorted(rs - gs)[:12]:
        print('   only ref: %#x -> %#x %s' % (f, t, [n for ff, tt, n in ref if ff == f]))
    gonly = sorted(gs - rs)
    for f, t in gonly[:12]:
        print('   only gen: %#x -> %#x %s' % (f, t, [n for ff, tt, n in rows if ff == f and tt == t]))
    # is ref a subset limited to some segment / range?
    if gonly:
        import collections
        print('   only-gen by from>>8:', sorted(collections.Counter(f >> 8 for f, _ in gonly).items())[:40])
        print('   ref from range: %#x..%#x' % (min(f for f, _ in rs), max(f for f, _ in rs)))
if a.emit:
    with open(a.emit, 'w') as o:
        o.write('#pragma once\n// Generated by dcn_remap_gen.py (%s): absolute dword register addresses.\n' % a.label)
        o.write('struct DcnRemap { uint32_t from, to; const char *name; };\nstatic const DcnRemap kDcnRemap[] {\n')
        seen = set()
        for f, t, n in rows:
            if f in seen:
                continue
            seen.add(f)
            o.write('\t{%#x, %#x, "%s"},\n' % (f, t, n))
        o.write('};\n')
    print('wrote', a.emit)
